from __future__ import annotations

import numpy as np

# D2Q9 lattice directions: rest, E, S, W, N, SE, SW, NW, NE  (y grows downward)
EX = np.array([0, 1, 0, -1, 0, 1, -1, -1, 1])
EY = np.array([0, 0, 1, 0, -1, 1, 1, -1, -1])
OPP = np.array([0, 3, 4, 1, 2, 7, 8, 5, 6])  # index of the opposite direction
W = np.array([4 / 9] + [1 / 9] * 4 + [1 / 36] * 4, dtype=np.float32)

_EXF = EX.astype(np.float32)[:, None, None]
_EYF = EY.astype(np.float32)[:, None, None]
_W3 = W[:, None, None]


def equilibrium(rho: np.ndarray, ux: np.ndarray, uy: np.ndarray) -> np.ndarray:
    """Maxwell-Boltzmann equilibrium populations, shape (9, *rho.shape)."""
    cu = 3.0 * (_EXF * ux + _EYF * uy)
    usq = 1.5 * (ux * ux + uy * uy)
    return (_W3 * rho * (1.0 + cu + 0.5 * cu * cu - usq)).astype(np.float32)


class WindTunnel:
    def __init__(self, nx: int = 400, ny: int = 100, u0: float = 0.1, viscosity: float = 0.02):
        self.nx, self.ny = nx, ny
        self.u0 = u0  # inlet speed, lattice units (keep well below ~0.3 for stability)
        self.viscosity = viscosity  # kinematic viscosity, lattice units
        self.obstacle = np.zeros((ny, nx), dtype=bool)
        self.steps = 0
        self.reset()

    # ------------------------------------------------------------------ state

    @property
    def omega(self) -> float:
        """BGK relaxation rate from viscosity: nu = (1/omega - 1/2) / 3."""
        return 1.0 / (3.0 * self.viscosity + 0.5)

    def reset(self) -> None:
        """Restart the flow as uniform free stream, keeping obstacles."""
        ny, nx = self.ny, self.nx
        rho = np.ones((ny, nx), np.float32)
        ux = np.full((ny, nx), self.u0, np.float32)
        uy = np.zeros((ny, nx), np.float32)
        # Tiny random perturbation so symmetric bodies start shedding vortices.
        uy += np.random.default_rng(0).normal(0, 1e-4, (ny, nx)).astype(np.float32)
        ux[self.obstacle] = 0
        uy[self.obstacle] = 0
        self.f = equilibrium(rho, ux, uy)
        self.steps = 0

    def is_finite(self) -> bool:
        return bool(np.isfinite(self.f.sum()))

    def macroscopic(self):
        f = self.f
        rho = f.sum(axis=0)
        with np.errstate(divide="ignore", invalid="ignore"):
            ux = (f[1] + f[5] + f[8] - f[3] - f[6] - f[7]) / rho
            uy = (f[2] + f[5] + f[6] - f[4] - f[7] - f[8]) / rho
        return rho, ux, uy

    # --------------------------------------------------------------- stepping

    def step(self, n: int = 1) -> None:
        # A blow-up shows as inf/NaN; callers check is_finite() rather than
        # flooding the log with floating-point warnings.
        with np.errstate(all="ignore"):
            self._step(n)

    def _step(self, n: int) -> None:
        f = self.f
        obs = self.obstacle
        omega = np.float32(self.omega)
        for _ in range(n):
            rho, ux, uy = self.macroscopic()

            # Collide (fluid cells only: obstacle cells hold bounced populations).
            saved = f[:, obs]
            f += omega * (equilibrium(rho, ux, uy) - f)
            f[:, obs] = saved

            # Stream: shift each population one cell along its direction.
            for i in range(1, 9):
                f[i] = np.roll(f[i], (EY[i], EX[i]), axis=(0, 1))

            # Bounce-back: populations that entered an obstacle reverse direction
            # and stream back out on the next step.
            if obs.any():
                f[:, obs] = f[:, obs][OPP]

            self._apply_boundaries()
            self.steps += 1

    def _apply_boundaries(self) -> None:
        f = self.f
        # Outlet (right): zero-gradient, lets the wake leave the domain.
        f[:, :, -1] = f[:, :, -2]
        # Inlet (left) and far-field (top/bottom): free-stream equilibrium.
        one = np.ones((1, 1), np.float32)
        feq = equilibrium(one, one * np.float32(self.u0), one * 0)[:, 0, :]  # (9, 1)
        f[:, :, 0] = feq
        f[:, 0, :] = feq
        f[:, -1, :] = feq

    # ----------------------------------------------------------------- fields

    def vorticity(self) -> np.ndarray:
        _, ux, uy = self.macroscopic()
        w = (np.roll(uy, -1, axis=1) - np.roll(uy, 1, axis=1)) - (
            np.roll(ux, -1, axis=0) - np.roll(ux, 1, axis=0)
        )
        w *= 0.5
        w[self.obstacle] = 0
        return w

    def speed(self) -> np.ndarray:
        _, ux, uy = self.macroscopic()
        s = np.sqrt(ux * ux + uy * uy)
        s[self.obstacle] = 0
        return s

    def pressure(self) -> np.ndarray:
        """Pressure deviation from the free stream (p = rho / 3 in lattice units)."""
        rho, _, _ = self.macroscopic()
        p = (rho - 1.0) / 3.0
        p[self.obstacle] = 0
        return p

    def reynolds(self) -> float:
        """Re based on the obstacle's cross-stream height."""
        height = int(self.obstacle.any(axis=1).sum())
        return self.u0 * height / self.viscosity if height else 0.0

    # -------------------------------------------------------------- obstacles

    def paint(self, x: float, y: float, r: float, solid: bool = True) -> None:
        """Add (or erase) a disc of obstacle cells centred at grid point (x, y)."""
        yy, xx = np.ogrid[: self.ny, : self.nx]
        mask = (xx - x) ** 2 + (yy - y) ** 2 <= r * r
        mask[:, :2] = False  # keep inlet/outlet columns open
        mask[:, -2:] = False
        if solid:
            changed = mask & ~self.obstacle
            self.obstacle |= mask
        else:
            changed = mask & self.obstacle
            self.obstacle &= ~mask
        if changed.any():
            n = int(changed.sum())
            rest = equilibrium(np.ones(n, np.float32), np.zeros(n, np.float32), np.zeros(n, np.float32))
            self.f[:, changed] = rest

    def set_obstacle(self, mask: np.ndarray) -> None:
        self.obstacle = mask.astype(bool)
        self.obstacle[:, :2] = False
        self.obstacle[:, -2:] = False
        self.reset()

    def load_preset(self, name: str) -> None:
        self.set_obstacle(PRESETS[name](self.nx, self.ny))


