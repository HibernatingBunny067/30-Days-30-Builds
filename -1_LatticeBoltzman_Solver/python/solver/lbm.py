def _grid(nx, ny):
    yy, xx = np.mgrid[:ny, :nx]
    return xx.astype(np.float32), yy.astype(np.float32)


def cylinder(nx: int, ny: int) -> np.ndarray:
    xx, yy = _grid(nx, ny)
    r = ny / 10
    # Offset by a cell so the wake breaks symmetry and sheds sooner.
    return (xx - nx / 5) ** 2 + (yy - ny / 2 - 1) ** 2 <= r * r


def airfoil(nx: int, ny: int, aoa_deg: float = 12.0) -> np.ndarray:
    """NACA 0012 at the given angle of attack (nose up)."""
    xx, yy = _grid(nx, ny)
    chord = nx * 0.25
    dx, dy = xx - nx * 0.18, yy - ny / 2
    a = np.radians(aoa_deg)
    xr = dx * np.cos(a) + dy * np.sin(a)  # along the chord
    yr = -dx * np.sin(a) + dy * np.cos(a)  # across the chord
    t = np.clip(xr / chord, 0, 1)
    half = 5 * 0.12 * chord * (0.2969 * np.sqrt(t) - 0.1260 * t - 0.3516 * t**2 + 0.2843 * t**3 - 0.1015 * t**4)
    return (xr >= 0) & (xr <= chord) & (np.abs(yr) <= half)


def plate(nx: int, ny: int) -> np.ndarray:
    xx, yy = _grid(nx, ny)
    return (np.abs(xx - nx / 5) <= 1) & (np.abs(yy - ny / 2) <= ny / 6)


def empty(nx: int, ny: int) -> np.ndarray:
    return np.zeros((ny, nx), dtype=bool)


PRESETS = {"cylinder": cylinder, "airfoil": airfoil, "plate": plate, "empty": empty}
